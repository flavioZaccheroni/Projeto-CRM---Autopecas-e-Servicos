@lru_cache(maxsize=1024)
def _pixmap(nome: str, cor: str, tamanho: int, dpr: float) -> QPixmap:
    corpo = _P.get(nome, _P["info"])
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{cor}" '
        f'stroke-width="2" stroke-linecap="round" stroke-linejoin="round">{corpo.replace("currentColor", cor)}</svg>'
    )
    lado = max(1, int(tamanho * dpr))
    imagem = QImage(lado, lado, QImage.Format.Format_ARGB32_Premultiplied)
    imagem.fill(Qt.GlobalColor.transparent)
    pintor = QPainter(imagem)
    pintor.setRenderHint(QPainter.RenderHint.Antialiasing)
    QSvgRenderer(QByteArray(svg.encode("utf-8"))).render(pintor, QRectF(0, 0, lado, lado))
    pintor.end()
    pixmap = QPixmap.fromImage(imagem)
    pixmap.setDevicePixelRatio(dpr)
    return pixmap


def pixmap(nome: str, cor: str, tamanho: int = 18, dpr: float = 2.0) -> QPixmap:
    return _pixmap(nome, cor, tamanho, dpr)


def icone(nome: str, cor: str, tamanho: int = 18) -> QIcon:
    return QIcon(pixmap(nome, cor, tamanho))


def nomes() -> list[str]:
    return sorted(_P)
